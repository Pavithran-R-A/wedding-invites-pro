const sha256 = (buffer) => createHash("sha256").update(buffer).digest("hex");
const OFL = "Copyright 2022 The Noto Project Authors\n\nThis Font Software is licensed under the "
  + "SIL Open Font License, Version 1.1.\n";

// --------------------------------------------------------------------------- the CSS reader

const UPSTREAM_BLOCK = `/* noto-sans-tamil-tamil-400-normal */
@font-face {
  font-family: 'Noto Sans Tamil';
  font-style: normal;
  font-display: swap;
  font-weight: 400;
  src: url(./files/noto-sans-tamil-tamil-400-normal.woff2) format('woff2'), url(./files/noto-sans-tamil-tamil-400-normal.woff) format('woff');
  unicode-range: U+0964-0965,U+0B82-0BFA,U+25CC;
}
`;

describe("@font-face reader", () => {
  it("reads the declarations a block commits to", () => {
    const [block] = parseFontFaceCss(UPSTREAM_BLOCK, "fixture");
    expect(block.label).toBe("noto-sans-tamil-tamil-400-normal");
    expect(faceFields(block, "fixture")).toEqual({
      label: "noto-sans-tamil-tamil-400-normal",
      url: "./files/noto-sans-tamil-tamil-400-normal.woff2",
      file: "files/noto-sans-tamil-tamil-400-normal.woff2",
      fontFamily: "Noto Sans Tamil",
      fontStyle: "normal",
      fontWeight: 400,
      unicodeRange: "U+0964-0965,U+0B82-0BFA,U+25CC",
    });
  });

  it("is the upstream block with the woff fallback removed and nothing else altered", () => {
    // The claim this pins is the one the design rests on: the committed stylesheet is a copy, so a
    // review of the upstream CSS is a review of what ships. A rewrite would let a formatting change
    // pass for a content change, or hide a dropped declaration.
    const [block] = parseFontFaceCss(UPSTREAM_BLOCK, "fixture");
    const withoutFallback = UPSTREAM_BLOCK
      .replace(", url(./files/noto-sans-tamil-tamil-400-normal.woff) format('woff')", "");
    expect(`${renderFontFace(block, "fixture")}\n`).toBe(withoutFallback);
  });

  it("keeps declaration order, including a block with no unicode-range", () => {
    const css = `@font-face {
  font-weight: 700;
  font-family: 'DM Sans';
  src: url(./files/dm-sans-latin-700-normal.woff2) format('woff2');
  font-display: swap;
  font-style: normal;
}`;
    const [block] = parseFontFaceCss(css, "fixture");
    expect(block.props.map((p) => p.name)).toEqual(["font-weight", "font-family", "src", "font-display", "font-style"]);
    expect(faceFields(block, "fixture").unicodeRange).toBeNull();
  });

  it("reads a generated header comment and does not mistake it for a face label", () => {
    const css = `/* Generated by scripts/fetch-render-fonts.mjs from @fontsource packages
 * at the versions recorded in the manifest. woff2 sources only.
 * Do not hand-edit. */
@font-face {
  font-family: 'DM Sans';
  font-style: normal;
  font-display: swap;
  font-weight: 400;
  src: url(./files/dm-sans-latin-400-normal.woff2) format('woff2');
}`;
    const blocks = parseFontFaceCss(css, "fixture");
    expect(blocks).toHaveLength(1);
    expect(blocks[0].label).toBeNull();
  });

  it("refuses a tree that changed shape rather than guessing at the new one", () => {
    const bad = [
      ["stray text", `@font-face {\n  font-family: 'X';\n}\nselector { color: red; }\n`],
      ["unterminated block", `@font-face {\n  font-family: 'X';\n`],
      ["nested block", `@font-face {\n@font-face {\n}\n}\n`],
      ["comment inside a block", `@font-face {\n/* label */\n  font-family: 'X';\n}\n`],
      ["not a declaration", `@font-face {\n  font-family 'X';\n}\n`],
      ["unterminated comment", `/* opens and never closes\n`],
      ["two labels in a row", `/* one */\n/* two */\n@font-face {\n  font-family: 'X';\n}\n`],
      ["closing brace with no block", `}\n`],
      ["label comment ending early", `/* a */ b */\n@font-face {\n  font-family: 'X';\n}\n`],
    ];
    for (const [name, css] of bad) {
      expect(() => parseFontFaceCss(css, "fixture"), name).toThrow(/fixture/);
    }
  });
});

describe("src reduction", () => {
  const pair = (url) => `url(${url}) format('woff2'), url(x.woff) format('woff')`;

  it("keeps the woff2 source", () => {
    expect(woff2Source(pair("./files/a.woff2"), "fixture")).toEqual({ url: "./files/a.woff2", file: "files/a.woff2" });
  });

  it("refuses every way a font can come from somewhere other than this origin", () => {
    // A blacklist is a list of the ways already thought of; this is a whitelist, so an unlisted form
    // is a refusal too. The `./`-prefixed escape is the one a plain `..` test would have missed.
    const urls = ["https://fonts.example.com/a.woff2", "//fonts.example.com/a.woff2",
      "/absolute/a.woff2", "../outside/a.woff2", "./../outside/a.woff2", "files/../a.woff2",
      "files\\a.woff2", "C:\\fonts\\a.woff2", "data:font/woff2;base64,AAAA", "a.WOFF2", "a.woff2 ", ""];
    for (const url of urls) {
      expect(() => woff2Source(pair(url), "fixture"), url).toThrow(/fixture: (refuses a font URL|src carries a form)/);
    }
  });

  it("refuses a format it was not told to handle instead of dropping it quietly", () => {
    expect(() => woff2Source(`url(./files/a.otf) format('opentype')`, "fixture")).toThrow(/will not silently drop/);
    expect(() => woff2Source(`url(./files/a.woff2)`, "fixture")).toThrow(/will not silently drop/);
    expect(() => woff2Source(`url() format('woff2')`, "fixture")).toThrow(/will not silently drop/);
    expect(() => woff2Source(`url(./a.woff2) format('woff2'), url(./b.woff2) format('woff2')`, "fixture"))
      .toThrow(/exactly one woff2 source, found 2/);
    expect(() => woff2Source(`url(./files/a.woff) format('woff')`, "fixture")).toThrow(/exactly one woff2 source, found 0/);
  });

  it("refuses a face that is not normal, not swap, or not a number", () => {
    const block = (overrides = {}) => {
      const base = {
        "font-family": "'DM Sans'",
        "font-style": "normal",
        "font-display": "swap",
        "font-weight": "400",
        src: "url(./files/a.woff2) format('woff2')",
      };
      const merged = { ...base, ...overrides };
      return {
        label: "x",
        props: Object.entries(merged).filter(([, value]) => value !== undefined).map(([name, value]) => ({ name, value })),
      };
    };
    expect(() => faceFields(block({ "font-style": "italic" }), "fixture")).toThrow(/non-normal style/);
    expect(() => faceFields(block({ "font-display": "block" }), "fixture")).toThrow(/refuses font-display block/);
    expect(() => faceFields(block({ "font-display": undefined }), "fixture")).toThrow(/expected swap/);
    expect(() => faceFields(block({ "font-weight": "bold" }), "fixture")).toThrow(/not a number/);
    expect(() => faceFields(block({ "font-family": undefined }), "fixture")).toThrow(/no font-family/);
    expect(faceFields(block(), "fixture").file).toBe("files/a.woff2");
  });
});

describe("stylesheet assembly", () => {
  it("refuses to write an empty stylesheet", () => {
    expect(() => renderFontsCss([])).toThrow(/no faces to write/);
  });

  it("separates blocks and ends with a newline, so a regeneration is byte-stable", () => {
    const [block] = parseFontFaceCss(UPSTREAM_BLOCK, "fixture");
    const css = renderFontsCss([block, block]);
    expect(css.startsWith("/* Generated by scripts/fetch-render-fonts.mjs")).toBe(true);
    expect(css.endsWith("}\n")).toBe(true);
    expect(css.split("\n\n")).toHaveLength(3);
    expect(renderFontsCss([block, block])).toBe(css);
  });
});

// --------------------------------------------------------------------------- the audit

/** One subset per family, so a fixture stays readable and still covers every pinned weight. */
function healthyTree() {
  const files = new Map();
  const families = FAMILIES.map(({ slug, cssFamily }) => ({
    package: `@fontsource/${slug}`,
    version: "5.3.0",
    cssFamily,
    license: "OFL-1.1",
    tarball: { url: `https://registry.example/${slug}.tgz`, bytes: 10, sha1: "a".repeat(40), sha512: "sha512-AA", registryIntegrity: "sha512-AA" },
    licence: { path: `public/fonts/licences/${slug}.txt`, bytes: Buffer.byteLength(OFL), sha256: sha256(Buffer.from(OFL)) },
    faces: WEIGHTS.map((weight) => {
      const name = `${slug}-latin-${weight}-normal.woff2`;
      const bytes = Buffer.from(`FONT:${name}`);
      return {
        label: name.replace(".woff2", ""),
        url: `./files/${name}`,
        file: `files/${name}`,
        path: `public/fonts/files/${name}`,
        bytes: bytes.length,
        sha256: sha256(bytes),
        fontFamily: cssFamily,
        fontStyle: "normal",
        fontWeight: weight,
        unicodeRange: "U+0000-00FF",
      };
    }),
  }));
  const css = renderFontsCss(families.flatMap((family) => family.faces.map((face) => ({
    label: face.label,
    props: [
      { name: "font-family", value: `'${face.fontFamily}'` },
      { name: "font-style", value: face.fontStyle },
      { name: "font-display", value: "swap" },
      { name: "font-weight", value: String(face.fontWeight) },
      { name: "src", value: `url(${face.url}) format('woff2')` },
      { name: "unicode-range", value: face.unicodeRange },
    ],
  }))));
  const manifest = {
    schema: 1,
    generatedBy: "scripts/fetch-render-fonts.mjs",
    registry: "https://registry.example",
    weights: WEIGHTS,
    css: { path: "public/fonts/fonts.css", bytes: Buffer.byteLength(css), sha256: sha256(Buffer.from(css)) },
    families,
  };

  for (const family of families) {
    files.set(family.licence.path, Buffer.from(OFL));
    for (const face of family.faces) files.set(face.path, Buffer.from(`FONT:${face.file.replace("files/", "")}`));
  }
  files.set("public/fonts/fonts.css", css);
  files.set(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
  files.set("index.html", `<link rel="stylesheet" href="/fonts/fonts.css" />\n`);
  files.set("src/pages/EditProject.tsx", `const FONT_FAMILIES = [${FAMILIES.map((f) => `'${f.cssFamily}'`).join(", ")}];\n`);
  files.set("src/index.css", `:root {\n  --font-body: ${FAMILIES.map((f) => `"${f.cssFamily}"`).join(", ")}, system-ui, sans-serif;\n}\n`);
  return { files, manifest, css };
}

function memoryView(files) {
  const map = files instanceof Map ? files : new Map(Object.entries(files));
  const under = (dir) => [...map.keys()].filter((p) => p.startsWith(`${dir}/`));
  return {
    exists: (p) => map.has(p) || under(p).length > 0,
    read: (p) => (Buffer.isBuffer(map.get(p)) ? map.get(p).toString("utf8") : String(map.get(p))),
    bytes: (p) => (Buffer.isBuffer(map.get(p)) ? map.get(p) : Buffer.from(String(map.get(p)))),
    files: (dir) => under(dir).filter((p) => !p.slice(dir.length + 1).includes("/")),
    entries: (p) => {
      if (map.has(p)) return [];
      const seen = new Map();
      for (const child of under(p)) {
        const rest = child.slice(p.length + 1);
        if (rest.includes("/")) seen.set(rest.split("/")[0], true);
        else if (!seen.has(rest)) seen.set(rest, false);
      }
      return [...seen].map(([name, dir]) => ({ name, dir }));
    },
  };
}

const rulesFor = (view) => auditRenderAssets(view).findings.map((f) => f.rule);

/** Audit a healthy tree with one thing changed, and report which rules fired. */
function rulesFrom(mutate) {
  const { files } = healthyTree();
  mutate(files, files.get(MANIFEST_PATH));
  return rulesFor(memoryView(files));
}

/** Rewrite the manifest inside a tree, re-signing the stylesheet digest unless the mutation says otherwise. */
const withManifest = (mutate) => (files) => {
  const manifest = JSON.parse(String(files.get(MANIFEST_PATH)));
  mutate(manifest, files);
  files.set(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
};

const withCssAndDigest = (mutateCss) => withManifest((manifest, files) => {
  const css = mutateCss(String(files.get("public/fonts/fonts.css")));
  files.set("public/fonts/fonts.css", css);
  manifest.css.sha256 = sha256(Buffer.from(css));
});

describe("render-asset audit", () => {
  it("accepts a tree that matches its manifest", () => {
    const { files, manifest } = healthyTree();
    const report = auditRenderAssets(memoryView(files));
    expect(report.findings).toEqual([]);
    expect(report.measures.at(-1)).toContain(`${manifest.families.length} families, 24 face(s)`);
  });

  it("reports a manifest that is missing or is not JSON", () => {
    const { files } = healthyTree();
    files.delete(MANIFEST_PATH);
    expect(rulesFor(memoryView(files))).toEqual(["manifest-missing"]);
    files.set(MANIFEST_PATH, "{ not json");
    expect(rulesFor(memoryView(files))).toEqual(["manifest-unparsable"]);
  });

  it("reports a face whose bytes changed after review without changing length", () => {
    // The byte count and the digest are separate rules for a reason: an edit that keeps the file the
    // same size is invisible to one of them. This is exactly that edit — first byte 'F' → 'A'.
    const path = "public/fonts/files/dm-sans-latin-400-normal.woff2";
    expect(rulesFrom((files) => {
      const bytes = files.get(path);
      bytes[0] = 0x41;
      files.set(path, bytes);
    })).toEqual(["face-digest"]);
  });

  it("reports a face whose length changed but whose digest was left alone", () => {
    expect(rulesFrom((files) => files.set("public/fonts/files/dm-sans-latin-400-normal.woff2", Buffer.from("X"))))
      .toEqual(["face-bytes", "face-digest"]);
  });

  it("reports a face the manifest promises and the tree does not carry", () => {
    expect(rulesFrom((files) => files.delete("public/fonts/files/dm-sans-latin-400-normal.woff2")))
      .toEqual(["face-missing"]);
  });

  it("reports a stray byte committed where the app would serve it", () => {
    // Both fire together, and that is the point: an unaccounted `.woff` is exactly what a rotation
    // leaves behind, and shipping it unreviewed is the finding.
    expect(rulesFrom((files) => files.set("public/fonts/files/old-face.woff", Buffer.from("X"))))
      .toEqual(["face-orphan", "face-unexpected-format"]);
  });

  it("reports a stylesheet that drifted from the manifest", () => {
    expect(rulesFrom((files) => files.set("public/fonts/fonts.css", `${files.get("public/fonts/fonts.css")}\n`)))
      .toContain("css-digest");
    expect(rulesFrom((files) => files.delete("public/fonts/fonts.css"))).toEqual(["css-missing"]);
    expect(rulesFrom((files) => files.set("public/fonts/fonts.css", "nonsense\n"))).toEqual(["css-digest", "css-unparsable"]);
  });

  it("reads the stylesheet both ways: a face nobody recorded, and a face nobody loads", () => {
    expect(rulesFrom(withCssAndDigest((css) => css
      .replace("url(./files/dm-sans-latin-400-normal.woff2)", "url(./files/unlisted-400-normal.woff2)"))))
      .toEqual(["css-face-unknown", "css-face-absent"]);
  });

  it("reports CSS that altered a face's family, weight, style, range, display or source format", () => {
    const drift = (mutateCss, rule) => expect(rulesFrom(withCssAndDigest(mutateCss))).toContain(rule);
    drift((css) => css.replace("  font-family: 'DM Sans';", "  font-family: 'Deja Vu Sans';"), "css-family");
    drift((css) => css.replace("  font-weight: 400;", "  font-weight: 900;"), "css-weight");
    drift((css) => css.replace("  font-style: normal;", "  font-style: italic;"), "css-style");
    drift((css) => css.replace("unicode-range: U+0000-00FF;", "unicode-range: U+0000-00FF,U+0100-017F;"), "css-range");
    drift((css) => css.replace("  font-display: swap;", "  font-display: block;"), "css-display");
    drift((css) => css.replace("format('woff2')", "format('opentype')"), "css-src");
  });

  it("reports a missing licence, an unlicensed licence, and a licence for a family nobody ships", () => {
    expect(rulesFrom((files) => files.delete("public/fonts/licences/dm-sans.txt"))).toEqual(["licence-missing"]);
    expect(rulesFrom((files) => files.set("public/fonts/licences/dm-sans.txt", "Proprietary. Do not redistribute.\n")))
      .toEqual(["licence-bytes", "licence-digest", "licence-text"]);
    expect(rulesFrom((files) => files.set("public/fonts/licences/ghost.txt", OFL))).toEqual(["licence-orphan"]);
  });

  it("reports a family the editor offers but no shipped face covers", () => {
    // The failure mode is silent: a guest page renders in a system font and the complaint reads as a
    // typography problem, so both the menu and the token stack are checked against what ships.
    expect(rulesFrom((files) => files.set("src/pages/EditProject.tsx",
      String(files.get("src/pages/EditProject.tsx")).replace("'DM Sans'", "'Comic Neue'"))))
      .toEqual(["family-unshipped"]);
    expect(rulesFrom((files) => files.set("src/index.css", ":root {\n  --font-body: Inter, sans-serif;\n}\n")))
      .toEqual(["family-unshipped"]);
    expect(rulesFrom((files) => files.set("src/pages/EditProject.tsx", "const FONT_FAMILIES = ;\n")))
      .toEqual(["typography-source-unparsable"]);
    expect(rulesFrom((files) => files.delete("src/index.css"))).toEqual(["typography-source-missing"]);
  });

  it("reports a remote font host that came back to the product surface", () => {
    expect(rulesFrom((files) => files.set("index.html",
      `${files.get("index.html")}<link rel="preconnect" href="https://fonts.gstatic.com" />\n`)))
      .toEqual(["font-cdn-reference"]);
  });

  it("reports a manifest that disagrees with the tool's own pins", () => {
    expect(rulesFrom(withManifest((m) => { m.schema = 2; }))).toEqual(["manifest-schema"]);
    expect(rulesFrom(withManifest((m) => { m.generatedBy = "by hand"; }))).toEqual(["manifest-author"]);
    expect(rulesFrom(withManifest((m) => { m.families[0].version = "5.2.0"; }))).toEqual(["family-version"]);
    expect(rulesFrom(withManifest((m) => { m.families[0].license = "MIT"; }))).toEqual(["family-licence"]);
    expect(rulesFrom(withManifest((m) => { m.css.sha256 = "0".repeat(64); }))).toEqual(["css-digest"]);
    // Dropping a family leaves its bytes, its licence and its CSS rules behind, each of which is
    // itself a finding — the point is that no part of a removal can be silently partial.
    expect(rulesFrom(withManifest((m) => { m.families.shift(); }))).toEqual(expect.arrayContaining([
      "family-missing", "face-orphan", "licence-orphan", "css-face-unknown", "css-count", "family-unshipped",
    ]));
    // The ghost family is a copy of DM Sans, so its faces carry DM Sans's own file names and family:
    // every stylesheet rule still matches a recorded face, and the only disagreement the CSS can see
    // is the count. The unpinning itself is caught against the tool's pins, not the stylesheet.
    expect(rulesFrom(withManifest((m) => {
      m.families.push({ ...m.families[0], package: "@fontsource/ghost", cssFamily: "Ghost" });
    }))).toEqual(["family-unpinned", "css-count"]);
  });

  it("reports a family missing a weight, and one shipping a weight the app never declared", () => {
    expect(rulesFrom(withManifest((m, files) => {
      m.families[0].faces = m.families[0].faces.filter((f) => f.fontWeight !== 600);
      files.delete("public/fonts/files/dm-sans-latin-600-normal.woff2");
    }))).toEqual(expect.arrayContaining(["weight-missing", "css-count", "css-face-unknown"]));
    expect(rulesFrom(withManifest((m) => { m.families[0].faces[0].fontWeight = 800; })))
      .toEqual(expect.arrayContaining(["weight-missing", "weight-unpinned", "css-weight"]));
  });

  it("names the line a needle sits on, and does not read its own directory", () => {
    const view = memoryView({
      "index.html": "line one\nline two names fonts.googleapis.com here\n",
      "src/app.ts": "const h = 'fonts.gstatic.com';\n",
      "src/deep/nested/file.css": "/* fonts.googleapis.com */\n",
      "scripts/check-render-assets.mjs": "const FONT_CDN_HOSTS = ['fonts.googleapis.com'];\n",
      "public/fonts/fonts.css": "/* fonts.googleapis.com is not referenced */\n",
    });
    expect(findNeedles(view, ["fonts.googleapis.com", "fonts.gstatic.com"])).toEqual([
      { path: "index.html", line: 2, needle: "fonts.googleapis.com" },
      { path: "src/app.ts", line: 1, needle: "fonts.gstatic.com" },
      { path: "src/deep/nested/file.css", line: 1, needle: "fonts.googleapis.com" },
    ]);
  });

  it("fails a product file naming a CDN host and discloses a test fixture that names one", () => {
    // The split carries one claim: a file the test runner includes is run under vitest and imported
    // by no entry, so naming the CDN hosts inside a hostile-input fixture cannot put a remote font
    // request into a bundle. Proved in both directions — a product file still fails, and a name the
    // runner's `include` glob does *not* match (`src/lib/sneaky.test.js`) still fails, so the
    // widening cannot quietly become a place to hide a request.
    const withFile = (path) => () => {
      const { files } = healthyTree();
      files.set(path, "const h = 'fonts.gstatic.com';\n");
      return auditRenderAssets(memoryView(files));
    };

    const product = withFile("src/render/remoteFontRequest.ts")();
    expect(product.findings.map((f) => f.rule)).toEqual(["font-cdn-reference"]);
    expect(product.findings[0].path).toBe("src/render/remoteFontRequest.ts");

    const unrun = withFile("src/lib/sneaky.test.js")();
    expect(unrun.findings.map((f) => f.rule)).toEqual(["font-cdn-reference"]);

    const { files } = healthyTree();
    files.set("src/render/renderRequest.test.ts", "const a = 'fonts.googleapis.com';\n");
    files.set("src/test/invitationFixture.ts", "const b = 'fonts.gstatic.com';\n");
    const report = auditRenderAssets(memoryView(files));
    expect(report.findings).toEqual([]);
    const productFacing = report.measures.find((m) => m.includes("in product-facing text"));
    const disclosed = report.measures.find((m) => m.includes("in test fixtures only"));
    expect(productFacing).toContain("0 reference(s)");
    expect(disclosed).toContain("2 reference(s)");
    expect(disclosed).toContain("src/render/renderRequest.test.ts");
    expect(disclosed).toContain("src/test/invitationFixture.ts");
  });

  it("is satisfied by the tree this repository actually carries", () => {
    // The fixtures prove the rules fire; this proves they are satisfied by what really ships, so a
    // rule cannot be tuned until an imaginary tree passes while the real one is quietly wrong.
    const report = scan();
    expect(report.findings).toEqual([]);
    expect(report.measures.at(-1)).toMatch(/72 face\(s\)/);
  });
});
